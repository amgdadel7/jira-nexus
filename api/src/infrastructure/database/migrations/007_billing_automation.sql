-- 007 · Subscription billing (simulated payments), automation rules and outgoing webhooks.

CREATE TABLE subscription (
  id                    integer PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  plan                  text        NOT NULL DEFAULT 'free' CHECK (plan IN ('free', 'standard', 'premium')),
  cycle                 text        NOT NULL DEFAULT 'monthly' CHECK (cycle IN ('monthly', 'annual')),
  status                text        NOT NULL DEFAULT 'active',
  trial_ends_at         timestamptz,
  trial_used            boolean     NOT NULL DEFAULT false,
  current_period_start  timestamptz,
  current_period_end    timestamptz,
  cancel_at_period_end  boolean     NOT NULL DEFAULT false,
  billing_email         text,
  company               text,
  updated_at            timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE subscription IS 'The site''s single subscription row (plan, cycle, trial, billing period).';
COMMENT ON COLUMN subscription.status IS 'active | trialing | past_due | canceled.';

CREATE TABLE payment_methods (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  brand       text        NOT NULL,
  last4       text        NOT NULL CHECK (last4 ~ '^\d{4}$'),
  exp_month   integer     NOT NULL CHECK (exp_month BETWEEN 1 AND 12),
  exp_year    integer     NOT NULL,
  holder      text        NOT NULL DEFAULT '',
  is_default  boolean     NOT NULL DEFAULT true,
  created_at  timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE payment_methods IS 'Saved cards (only brand, last 4 digits and expiry are kept).';

CREATE TABLE invoices (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  number          text        NOT NULL UNIQUE,
  plan            text        NOT NULL,
  cycle           text        NOT NULL,
  seats           integer     NOT NULL,
  lines           jsonb       NOT NULL DEFAULT '[]'::jsonb,
  subtotal_cents  integer     NOT NULL,
  total_cents     integer     NOT NULL,
  status          text        NOT NULL DEFAULT 'paid' CHECK (status IN ('paid', 'open', 'void')),
  card            text,
  period_start    timestamptz,
  period_end      timestamptz,
  created_at      timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE invoices IS 'Invoices (MSR-YYYY-NNNNN) with line items in cents.';

CREATE TABLE automation_rules (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_key  text        NOT NULL REFERENCES projects (key) ON DELETE CASCADE ON UPDATE CASCADE,
  name         text        NOT NULL,
  description  text        NOT NULL DEFAULT '',
  enabled      boolean     NOT NULL DEFAULT true,
  trigger      jsonb       NOT NULL,
  condition    text        NOT NULL DEFAULT '',
  actions      jsonb       NOT NULL DEFAULT '[]'::jsonb,
  created_by   text        REFERENCES users (id) ON DELETE SET NULL,
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX automation_rules_project_idx ON automation_rules (project_key);
COMMENT ON TABLE automation_rules IS 'When <trigger> if <JQL condition> then <actions>.';
COMMENT ON COLUMN automation_rules.trigger IS '{"type": "issue_transitioned", "from": "To Do", "to": "In Progress"} …';

CREATE TABLE automation_runs (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rule_id      integer     NOT NULL REFERENCES automation_rules (id) ON DELETE CASCADE,
  issue_key    text,
  status       text        NOT NULL CHECK (status IN ('success', 'some_errors', 'failure', 'no_actions', 'throttled')),
  message      text        NOT NULL DEFAULT '',
  actions      jsonb       NOT NULL DEFAULT '[]'::jsonb,
  duration_ms  integer     NOT NULL DEFAULT 0,
  created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX automation_runs_rule_idx ON automation_runs (rule_id, created_at);
CREATE INDEX automation_runs_created_idx ON automation_runs (created_at);
COMMENT ON TABLE automation_runs IS 'Automation audit log: one row per rule execution.';

CREATE TABLE webhooks (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        text        NOT NULL,
  url         text        NOT NULL,
  secret      text        NOT NULL DEFAULT '',
  events      text[]      NOT NULL DEFAULT '{}',
  jql         text        NOT NULL DEFAULT '',
  enabled     boolean     NOT NULL DEFAULT true,
  created_by  text        REFERENCES users (id) ON DELETE SET NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE webhooks IS 'Outgoing webhooks (Jira-format payloads, HMAC-SHA256 signed when a secret is set).';

CREATE TABLE webhook_deliveries (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  webhook_id   integer     NOT NULL REFERENCES webhooks (id) ON DELETE CASCADE,
  uuid         text        NOT NULL,
  event        text        NOT NULL,
  payload      jsonb       NOT NULL,
  status_code  integer,
  ok           boolean     NOT NULL DEFAULT false,
  duration_ms  integer     NOT NULL DEFAULT 0,
  error        text,
  response     text,
  attempt      integer     NOT NULL DEFAULT 1,
  created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX webhook_deliveries_hook_idx ON webhook_deliveries (webhook_id, id);
COMMENT ON TABLE webhook_deliveries IS 'Delivery log (last 200 per webhook) incl. retries (attempt) and redeliveries (same uuid).';
