-- 011 · Permissions, MFA & Session Lifecycle

-- 1. MFA columns on users
ALTER TABLE users ADD COLUMN IF NOT EXISTS mfa_enabled boolean NOT NULL DEFAULT false;
ALTER TABLE users ADD COLUMN IF NOT EXISTS mfa_secret text;
ALTER TABLE users ADD COLUMN IF NOT EXISTS mfa_enrolled_at timestamptz;

-- 2. Hashed one-time backup / recovery codes
CREATE TABLE IF NOT EXISTS mfa_backup_codes (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     text NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  code_hash   text NOT NULL,
  used_at     timestamptz,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS mfa_backup_codes_user_idx ON mfa_backup_codes (user_id);
COMMENT ON TABLE mfa_backup_codes IS 'Hashed one-time recovery codes for multi-factor authentication.';

-- 3. Ephemeral login challenges for 2-step verification
CREATE TABLE IF NOT EXISTS mfa_challenges (
  token_hash   text PRIMARY KEY,
  user_id      text NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  remember     boolean NOT NULL DEFAULT true,
  user_agent   text NOT NULL DEFAULT '',
  ip_address   text NOT NULL DEFAULT '',
  attempts     integer NOT NULL DEFAULT 0,
  expires_at   timestamptz NOT NULL,
  created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS mfa_challenges_user_idx ON mfa_challenges (user_id);
COMMENT ON TABLE mfa_challenges IS 'Temporary login challenges pending 2FA code verification, valid 5 minutes.';

-- 4. Session tracking & sudo mode
ALTER TABLE sessions ADD COLUMN IF NOT EXISTS ip_address text NOT NULL DEFAULT '';
ALTER TABLE sessions ADD COLUMN IF NOT EXISTS device_name text NOT NULL DEFAULT '';
ALTER TABLE sessions ADD COLUMN IF NOT EXISTS sudo_confirmed_at timestamptz;
