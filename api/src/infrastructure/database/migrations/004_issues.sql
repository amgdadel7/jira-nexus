-- 004 · Work items and everything attached to them.

CREATE TABLE issues (
  id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key                 text        NOT NULL UNIQUE,
  num                 integer     NOT NULL,
  project_key         text        NOT NULL REFERENCES projects (key) ON UPDATE CASCADE,
  issue_type_id       integer     NOT NULL REFERENCES issue_types (id),
  summary             text        NOT NULL CHECK (length(summary) BETWEEN 1 AND 255),
  description         text        NOT NULL DEFAULT '',
  status_id           integer     NOT NULL REFERENCES statuses (id),
  priority_id         integer     NOT NULL REFERENCES priorities (id),
  resolution_id       integer     REFERENCES resolutions (id) ON DELETE SET NULL,
  assignee_id         text        REFERENCES users (id) ON DELETE SET NULL,
  reporter_id         text        REFERENCES users (id) ON DELETE SET NULL,
  parent_id           integer     REFERENCES issues (id) ON DELETE SET NULL,
  sprint_id           integer     REFERENCES sprints (id) ON DELETE SET NULL,
  fix_version_id      integer     REFERENCES versions (id) ON DELETE SET NULL,
  team_id             integer     REFERENCES teams (id) ON DELETE SET NULL,
  due_date            date,
  start_date          date,
  story_points        double precision CHECK (story_points IS NULL OR story_points BETWEEN 0 AND 1000),
  rank                double precision NOT NULL,
  original_estimate   integer     CHECK (original_estimate IS NULL OR original_estimate >= 0),
  remaining_estimate  integer     CHECK (remaining_estimate IS NULL OR remaining_estimate >= 0),
  time_spent          integer     NOT NULL DEFAULT 0 CHECK (time_spent >= 0),
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now(),
  resolved_at         timestamptz,
  UNIQUE (project_key, num),
  CHECK (parent_id IS NULL OR parent_id <> id)
);
CREATE INDEX issues_project_idx ON issues (project_key);
CREATE INDEX issues_rank_idx ON issues (rank);
CREATE INDEX issues_sprint_idx ON issues (sprint_id);
CREATE INDEX issues_parent_idx ON issues (parent_id);
CREATE INDEX issues_assignee_idx ON issues (assignee_id);
CREATE INDEX issues_status_idx ON issues (status_id);
CREATE INDEX issues_fix_version_idx ON issues (fix_version_id);
COMMENT ON TABLE issues IS 'Work items (epics, stories, tasks, bugs, sub-tasks).';
COMMENT ON COLUMN issues.key IS 'Human key, project key + number (KAN-12).';
COMMENT ON COLUMN issues.rank IS 'Global ordering used by backlog, board and "ORDER BY Rank" (cf[10019]).';
COMMENT ON COLUMN issues.original_estimate IS 'Original estimate in seconds (1d = 8h, 1w = 5d).';
COMMENT ON COLUMN issues.remaining_estimate IS 'Remaining estimate in seconds.';
COMMENT ON COLUMN issues.time_spent IS 'Total of all worklogs in seconds (kept in sync by the worklog service).';
COMMENT ON COLUMN issues.resolved_at IS 'When the item entered a done-category status; NULL while open.';

CREATE TABLE labels (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        text        NOT NULL CHECK (name ~ '^\S{1,60}$'),
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX labels_name_uq ON labels (lower(name));
COMMENT ON TABLE labels IS 'Site-wide label dictionary (labels have no spaces).';

CREATE TABLE issue_labels (
  issue_id  integer NOT NULL REFERENCES issues (id) ON DELETE CASCADE,
  label_id  integer NOT NULL REFERENCES labels (id) ON DELETE CASCADE,
  position  integer NOT NULL DEFAULT 0,
  PRIMARY KEY (issue_id, label_id)
);
CREATE INDEX issue_labels_label_idx ON issue_labels (label_id);

CREATE TABLE issue_components (
  issue_id      integer NOT NULL REFERENCES issues (id) ON DELETE CASCADE,
  component_id  integer NOT NULL REFERENCES components (id) ON DELETE CASCADE,
  position      integer NOT NULL DEFAULT 0,
  PRIMARY KEY (issue_id, component_id)
);
CREATE INDEX issue_components_component_idx ON issue_components (component_id);

CREATE TABLE comments (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  issue_id    integer     NOT NULL REFERENCES issues (id) ON DELETE CASCADE,
  author_id   text        REFERENCES users (id) ON DELETE SET NULL,
  body        text        NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX comments_issue_idx ON comments (issue_id);

CREATE TABLE history (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  issue_id    integer     NOT NULL REFERENCES issues (id) ON DELETE CASCADE,
  author_id   text        REFERENCES users (id) ON DELETE SET NULL,
  field       text        NOT NULL,
  from_value  text,
  to_value    text,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX history_issue_idx ON history (issue_id);
COMMENT ON TABLE history IS 'Change log of a work item (field, from → to, who, when).';

CREATE TABLE watchers (
  issue_id  integer NOT NULL REFERENCES issues (id) ON DELETE CASCADE,
  user_id   text    NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  PRIMARY KEY (issue_id, user_id)
);
CREATE INDEX watchers_user_idx ON watchers (user_id);

CREATE TABLE votes (
  issue_id    integer     NOT NULL REFERENCES issues (id) ON DELETE CASCADE,
  user_id     text        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  created_at  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (issue_id, user_id)
);

CREATE TABLE issue_links (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_id   integer     NOT NULL REFERENCES issues (id) ON DELETE CASCADE,
  target_id   integer     NOT NULL REFERENCES issues (id) ON DELETE CASCADE,
  type        text        NOT NULL CHECK (type IN ('blocks', 'relates', 'duplicates', 'clones')),
  created_by  text        REFERENCES users (id) ON DELETE SET NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (source_id, target_id, type),
  CHECK (source_id <> target_id)
);
CREATE INDEX issue_links_target_idx ON issue_links (target_id);
COMMENT ON TABLE issue_links IS 'Directed links: source <type> target (KAN-7 blocks KAN-4).';

CREATE TABLE attachments (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  issue_id     integer     NOT NULL REFERENCES issues (id) ON DELETE CASCADE,
  filename     text        NOT NULL,
  mime         text        NOT NULL,
  size         integer     NOT NULL CHECK (size >= 0),
  stored_name  text        NOT NULL,
  uploader_id  text        REFERENCES users (id) ON DELETE SET NULL,
  created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX attachments_issue_idx ON attachments (issue_id);
COMMENT ON COLUMN attachments.stored_name IS 'Random file name on disk (UPLOAD_DIR).';

CREATE TABLE worklogs (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  issue_id    integer     NOT NULL REFERENCES issues (id) ON DELETE CASCADE,
  author_id   text        REFERENCES users (id) ON DELETE SET NULL,
  started_at  timestamptz NOT NULL,
  time_spent  integer     NOT NULL CHECK (time_spent > 0),
  comment     text        NOT NULL DEFAULT '',
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX worklogs_issue_idx ON worklogs (issue_id);
CREATE INDEX worklogs_started_idx ON worklogs (started_at);
COMMENT ON TABLE worklogs IS 'Time logged on work items (seconds).';

CREATE TABLE dev_items (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  issue_id    integer     REFERENCES issues (id) ON DELETE CASCADE,
  kind        text        NOT NULL CHECK (kind IN ('branch', 'commit', 'pr')),
  repo        text        NOT NULL,
  name        text        NOT NULL,
  ref         text,
  status      text,
  author_id   text        REFERENCES users (id) ON DELETE SET NULL,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX dev_items_issue_idx ON dev_items (issue_id);
COMMENT ON TABLE dev_items IS 'Development panel: branches, commits and pull requests linked to work items.';
COMMENT ON COLUMN dev_items.status IS 'PR: open | merged | declined · branch: active.';

CREATE TABLE notifications (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     text        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  actor_id    text        REFERENCES users (id) ON DELETE SET NULL,
  issue_id    integer     REFERENCES issues (id) ON DELETE CASCADE,
  type        text        NOT NULL,
  message     text        NOT NULL,
  read        boolean     NOT NULL DEFAULT false,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX notifications_user_idx ON notifications (user_id, read);
COMMENT ON COLUMN notifications.type IS 'assigned | status | comment | mention.';
