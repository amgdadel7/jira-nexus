-- 003 · Projects, people & permissions, components, board, teams, sprints and releases.

CREATE TABLE projects (
  key              text PRIMARY KEY CHECK (key ~ '^[A-Z][A-Z0-9]{1,9}$'),
  name             text        NOT NULL,
  type             text        NOT NULL DEFAULT 'software' CHECK (type IN ('software', 'business', 'service')),
  description      text        NOT NULL DEFAULT '',
  lead_id          text        REFERENCES users (id) ON DELETE SET NULL,
  color            text        NOT NULL DEFAULT '#FFAB00',
  category         text        NOT NULL DEFAULT '',
  access           text        NOT NULL DEFAULT 'open' CHECK (access IN ('open', 'limited', 'private')),
  workflow_id      integer     NOT NULL REFERENCES workflows (id),
  custom_permissions boolean   NOT NULL DEFAULT false,
  board_swimlanes  text        NOT NULL DEFAULT 'none' CHECK (board_swimlanes IN ('none', 'assignee', 'epic', 'priority', 'type')),
  next_num         integer     NOT NULL DEFAULT 1,
  created_at       timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX projects_name_uq ON projects (lower(name));
COMMENT ON TABLE projects IS 'Spaces that hold work items. key is the work item key prefix (KAN → KAN-12).';
COMMENT ON COLUMN projects.access IS 'open: everyone is a member · limited: everyone can view · private: only added people.';
COMMENT ON COLUMN projects.workflow_id IS 'Workflow (statuses + transitions) used by this project''s work items and board.';
COMMENT ON COLUMN projects.custom_permissions IS 'True when the project uses its own permission scheme (permission_scheme_entries) instead of the default.';
COMMENT ON COLUMN projects.next_num IS 'Next work item number (the 12 in KAN-12).';

CREATE TABLE project_members (
  project_key  text        NOT NULL REFERENCES projects (key) ON DELETE CASCADE ON UPDATE CASCADE,
  user_id      text        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  role         text        NOT NULL CHECK (role IN ('admin', 'member', 'viewer')),
  added_by     text        REFERENCES users (id) ON DELETE SET NULL,
  added_at     timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (project_key, user_id)
);
CREATE INDEX project_members_user_idx ON project_members (user_id);
COMMENT ON TABLE project_members IS 'Project roles: Administrator, Member or Viewer. The lead is always an administrator.';

CREATE TABLE permission_scheme_entries (
  project_key  text NOT NULL REFERENCES projects (key) ON DELETE CASCADE ON UPDATE CASCADE,
  permission   text NOT NULL,
  role         text NOT NULL CHECK (role IN ('admin', 'member', 'viewer')),
  PRIMARY KEY (project_key, permission, role)
);
COMMENT ON TABLE permission_scheme_entries IS 'Customised permission scheme of a project. A project with no rows uses the default scheme.';

CREATE TABLE project_stars (
  user_id      text NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  project_key  text NOT NULL REFERENCES projects (key) ON DELETE CASCADE ON UPDATE CASCADE,
  starred_at   timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, project_key)
);
COMMENT ON TABLE project_stars IS 'Projects a user starred (shown first in the sidebar).';

CREATE TABLE components (
  id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_key       text        NOT NULL REFERENCES projects (key) ON DELETE CASCADE ON UPDATE CASCADE,
  name              text        NOT NULL,
  description       text        NOT NULL DEFAULT '',
  lead_id           text        REFERENCES users (id) ON DELETE SET NULL,
  default_assignee  text        NOT NULL DEFAULT 'unassigned' CHECK (default_assignee IN ('unassigned', 'component_lead', 'project_lead')),
  created_at        timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX components_name_uq ON components (project_key, lower(name));
COMMENT ON TABLE components IS 'Project components (e.g. Payments, Reporting) with an optional default assignee.';

CREATE TABLE board_column_limits (
  project_key  text    NOT NULL REFERENCES projects (key) ON DELETE CASCADE ON UPDATE CASCADE,
  status_id    integer NOT NULL REFERENCES statuses (id) ON DELETE CASCADE,
  wip_limit    integer NOT NULL CHECK (wip_limit > 0),
  PRIMARY KEY (project_key, status_id)
);
COMMENT ON TABLE board_column_limits IS 'Work-in-progress limits per board column (status).';

CREATE TABLE teams (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         text        NOT NULL,
  description  text        NOT NULL DEFAULT '',
  color        text        NOT NULL DEFAULT '#0C66E4',
  created_by   text        REFERENCES users (id) ON DELETE SET NULL,
  created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX teams_name_uq ON teams (lower(name));
COMMENT ON TABLE teams IS 'Cross-project teams; work items can be assigned to a team.';

CREATE TABLE team_members (
  team_id  integer NOT NULL REFERENCES teams (id) ON DELETE CASCADE,
  user_id  text    NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  PRIMARY KEY (team_id, user_id)
);

CREATE TABLE sprints (
  id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_key       text        NOT NULL REFERENCES projects (key) ON DELETE CASCADE ON UPDATE CASCADE,
  name              text        NOT NULL,
  goal              text        NOT NULL DEFAULT '',
  state             text        NOT NULL DEFAULT 'future' CHECK (state IN ('future', 'active', 'closed')),
  start_date        date,
  end_date          date,
  completed_at      timestamptz,
  position          integer     NOT NULL DEFAULT 0,
  committed_points  double precision,
  committed_count   integer,
  completed_points  double precision,
  completed_count   integer,
  created_at        timestamptz NOT NULL DEFAULT now(),
  CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date)
);
CREATE UNIQUE INDEX sprints_name_uq ON sprints (lower(name));
CREATE UNIQUE INDEX sprints_one_active_uq ON sprints (project_key) WHERE state = 'active';
COMMENT ON TABLE sprints IS 'Scrum sprints. At most one active sprint per project.';
COMMENT ON COLUMN sprints.committed_points IS 'Story points in the sprint when it started (velocity chart).';
COMMENT ON COLUMN sprints.completed_points IS 'Story points done when the sprint was completed.';

CREATE TABLE versions (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_key   text        NOT NULL REFERENCES projects (key) ON DELETE CASCADE ON UPDATE CASCADE,
  name          text        NOT NULL,
  description   text        NOT NULL DEFAULT '',
  status        text        NOT NULL DEFAULT 'unreleased' CHECK (status IN ('unreleased', 'released', 'archived')),
  start_date    date,
  release_date  date,
  released_at   timestamptz,
  position      integer     NOT NULL DEFAULT 0,
  created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX versions_name_uq ON versions (project_key, lower(name));
COMMENT ON TABLE versions IS 'Releases (fix versions) of a project.';
