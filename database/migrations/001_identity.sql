-- 001 · Identity: users, preferences, sessions, tokens, sign-up and social login, site settings.

CREATE TABLE users (
  id              text PRIMARY KEY,
  name            text        NOT NULL,
  email           text        NOT NULL,
  color           text        NOT NULL DEFAULT '#0C66E4',
  password_hash   text,
  role            text        NOT NULL DEFAULT 'member' CHECK (role IN ('admin', 'member')),
  active          boolean     NOT NULL DEFAULT true,
  title           text        NOT NULL DEFAULT '',
  avatar          text,
  bot             boolean     NOT NULL DEFAULT false,
  email_verified  boolean     NOT NULL DEFAULT true,
  signup_source   text        NOT NULL DEFAULT 'invite',
  created_at      timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX users_email_lower_uq ON users (lower(email));
COMMENT ON TABLE users IS 'People who can sign in, plus bot accounts (e.g. the automation actor).';
COMMENT ON COLUMN users.id IS 'Stable user id (u1, u2 … or u_<random> for new users).';
COMMENT ON COLUMN users.email IS 'Login e-mail, unique case-insensitively.';
COMMENT ON COLUMN users.password_hash IS 'scrypt hash "salt:hash"; NULL for social-only accounts and bots.';
COMMENT ON COLUMN users.role IS 'Site role: admin (site administrator) or member.';
COMMENT ON COLUMN users.active IS 'Deactivated users cannot sign in and are hidden from pickers.';
COMMENT ON COLUMN users.avatar IS 'Stored file name of the uploaded profile photo (served from /api/avatars).';
COMMENT ON COLUMN users.bot IS 'True for system actors such as "Automation for Masar".';
COMMENT ON COLUMN users.signup_source IS 'invite | signup | google | microsoft | apple | slack | seed.';

CREATE TABLE user_preferences (
  user_id        text        PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
  theme          text        NOT NULL DEFAULT 'light' CHECK (theme IN ('light', 'dark', 'system')),
  reduce_motion  boolean     NOT NULL DEFAULT false,
  week_start     text        NOT NULL DEFAULT 'sunday' CHECK (week_start IN ('sunday', 'monday', 'saturday')),
  notify         jsonb       NOT NULL DEFAULT '{}'::jsonb,
  updated_at     timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE user_preferences IS 'Personal settings: theme, motion, week start and notification switches.';
COMMENT ON COLUMN user_preferences.notify IS 'Map of notification type → enabled, e.g. {"comment": false}. Missing = enabled.';

CREATE TABLE sessions (
  token         text        PRIMARY KEY,
  user_id       text        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  user_agent    text        NOT NULL DEFAULT '',
  remember      boolean     NOT NULL DEFAULT true,
  created_at    timestamptz NOT NULL DEFAULT now(),
  last_seen_at  timestamptz,
  expires_at    timestamptz NOT NULL
);
CREATE INDEX sessions_user_idx ON sessions (user_id);
COMMENT ON TABLE sessions IS 'Browser sessions. The token travels as Bearer header, X-Auth-Token, ?access_token or cookie.';
COMMENT ON COLUMN sessions.remember IS 'Remember me: 14-day session instead of 12 hours.';

CREATE TABLE api_tokens (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       text        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  name          text        NOT NULL,
  token_hash    text        NOT NULL UNIQUE,
  prefix        text        NOT NULL,
  created_at    timestamptz NOT NULL DEFAULT now(),
  last_used_at  timestamptz,
  expires_at    timestamptz
);
CREATE INDEX api_tokens_user_idx ON api_tokens (user_id);
COMMENT ON TABLE api_tokens IS 'Personal access tokens (jcpat_…) for scripts; only the SHA-256 hash is stored.';

CREATE TABLE password_resets (
  token_hash  text        PRIMARY KEY,
  user_id     text        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  created_at  timestamptz NOT NULL DEFAULT now(),
  expires_at  timestamptz NOT NULL,
  used_at     timestamptz
);
COMMENT ON TABLE password_resets IS 'One-time password reset links (hash of the token in the e-mailed link).';

CREATE TABLE email_verifications (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email         text        NOT NULL,
  code_hash     text        NOT NULL,
  attempts      integer     NOT NULL DEFAULT 0,
  created_at    timestamptz NOT NULL DEFAULT now(),
  expires_at    timestamptz NOT NULL,
  verified_at   timestamptz,
  signup_token  text UNIQUE,
  used_at       timestamptz
);
CREATE INDEX email_verifications_email_idx ON email_verifications (lower(email));
COMMENT ON TABLE email_verifications IS 'Sign-up: 6-digit e-mail codes and the short-lived token that finishes the sign-up.';

CREATE TABLE user_identities (
  provider       text        NOT NULL,
  subject        text        NOT NULL,
  user_id        text        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  email          text,
  created_at     timestamptz NOT NULL DEFAULT now(),
  last_login_at  timestamptz,
  PRIMARY KEY (provider, subject)
);
CREATE INDEX user_identities_user_idx ON user_identities (user_id);
COMMENT ON TABLE user_identities IS 'Social accounts (Google, Microsoft, Apple, Slack) linked to a user.';

CREATE TABLE oauth_states (
  state       text        PRIMARY KEY,
  provider    text        NOT NULL,
  mode        text        NOT NULL DEFAULT 'login',
  popup       boolean     NOT NULL DEFAULT false,
  remember    boolean     NOT NULL DEFAULT true,
  nonce       text,
  created_at  timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE oauth_states IS 'Pending OAuth authorisation requests (CSRF state + OIDC nonce), valid 10 minutes.';

CREATE TABLE site_settings (
  key         text        PRIMARY KEY,
  value       jsonb       NOT NULL,
  updated_at  timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE site_settings IS 'Site-wide settings: sign-up policy, OAuth providers, global permission scheme …';
