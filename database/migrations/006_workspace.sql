-- 006 · Workspace: saved filters, goals, forms, dashboards, recycle bin and the audit log.

CREATE TABLE filters (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         text        NOT NULL,
  description  text        NOT NULL DEFAULT '',
  jql          text        NOT NULL,
  owner_id     text        REFERENCES users (id) ON DELETE CASCADE,
  starred      boolean     NOT NULL DEFAULT false,
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX filters_owner_idx ON filters (owner_id);
COMMENT ON TABLE filters IS 'Saved JQL filters.';

CREATE TABLE goals (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         text        NOT NULL,
  description  text        NOT NULL DEFAULT '',
  status       text        NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'on_track', 'at_risk', 'off_track', 'done', 'cancelled')),
  owner_id     text        REFERENCES users (id) ON DELETE SET NULL,
  target_date  date,
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE goals IS 'Company goals; progress is derived from the linked work items.';

CREATE TABLE goal_issues (
  goal_id   integer NOT NULL REFERENCES goals (id) ON DELETE CASCADE,
  issue_id  integer NOT NULL REFERENCES issues (id) ON DELETE CASCADE,
  PRIMARY KEY (goal_id, issue_id)
);

CREATE TABLE forms (
  id                   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_key          text        NOT NULL REFERENCES projects (key) ON DELETE CASCADE ON UPDATE CASCADE,
  name                 text        NOT NULL,
  description          text        NOT NULL DEFAULT '',
  issue_type_id        integer     NOT NULL REFERENCES issue_types (id),
  fields               jsonb       NOT NULL DEFAULT '[]'::jsonb,
  default_labels       text[]      NOT NULL DEFAULT '{}',
  default_assignee_id  text        REFERENCES users (id) ON DELETE SET NULL,
  active               boolean     NOT NULL DEFAULT true,
  submissions          integer     NOT NULL DEFAULT 0,
  created_by           text        REFERENCES users (id) ON DELETE SET NULL,
  created_at           timestamptz NOT NULL DEFAULT now(),
  updated_at           timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE forms IS 'Intake forms that create work items when submitted.';
COMMENT ON COLUMN forms.fields IS 'Ordered form questions: [{id, label, type, required, maps}].';

CREATE TABLE dashboards (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         text        NOT NULL,
  description  text        NOT NULL DEFAULT '',
  owner_id     text        REFERENCES users (id) ON DELETE CASCADE,
  shared       boolean     NOT NULL DEFAULT false,
  layout       text        NOT NULL DEFAULT 'two_column' CHECK (layout IN ('one_column', 'two_column', 'three_column')),
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX dashboards_owner_idx ON dashboards (owner_id);
COMMENT ON TABLE dashboards IS 'Personal or shared dashboards made of gadgets.';

CREATE TABLE dashboard_gadgets (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dashboard_id  integer     NOT NULL REFERENCES dashboards (id) ON DELETE CASCADE,
  type          text        NOT NULL,
  title         text        NOT NULL DEFAULT '',
  column_index  integer     NOT NULL DEFAULT 0 CHECK (column_index BETWEEN 0 AND 2),
  position      integer     NOT NULL DEFAULT 0,
  config        jsonb       NOT NULL DEFAULT '{}'::jsonb,
  created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX dashboard_gadgets_dashboard_idx ON dashboard_gadgets (dashboard_id);
COMMENT ON COLUMN dashboard_gadgets.type IS 'Gadget kind: stats, assigned, status_chart, workload, filter_results, activity, created_vs_resolved, sprint_progress …';
COMMENT ON COLUMN dashboard_gadgets.config IS 'Gadget settings, e.g. {"filterId": 3, "project": "KAN"}.';

CREATE TABLE trash (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_key  text        NOT NULL,
  issue_key    text        NOT NULL,
  summary      text        NOT NULL,
  type         text        NOT NULL,
  snapshot     jsonb       NOT NULL,
  files        jsonb       NOT NULL DEFAULT '[]'::jsonb,
  deleted_by   text        REFERENCES users (id) ON DELETE SET NULL,
  deleted_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX trash_project_idx ON trash (project_key, deleted_at);
COMMENT ON TABLE trash IS 'Recycle bin: full snapshot of deleted work items (with sub-tasks, comments, files) for restore.';

CREATE TABLE audit_log (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id     text        REFERENCES users (id) ON DELETE SET NULL,
  action       text        NOT NULL,
  project_key  text,
  target       text,
  details      jsonb       NOT NULL DEFAULT '{}'::jsonb,
  created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX audit_log_project_idx ON audit_log (project_key, created_at);
CREATE INDEX audit_log_action_idx ON audit_log (action);
COMMENT ON TABLE audit_log IS 'Administrative changes (settings, people, permissions, deletions, automation, webhooks …).';
