-- 001 · Identity: users, preferences, sessions, tokens, sign-up and social login, site settings.

CREATE TABLE users (
  id              text PRIMARY KEY,
  name            text        NOT NULL,
  email           text        NOT NULL,
  color           text        NOT NULL DEFAULT '#0C66E4',
  password_hash   text,
  role            text        NOT NULL DEFAULT 'member' CHECK (role IN ('admin', 'member')),
  active          boolean     NOT NULL DEFAULT true,
  title           text        NOT NULL DEFAULT '',
  avatar          text,
  bot             boolean     NOT NULL DEFAULT false,
  email_verified  boolean     NOT NULL DEFAULT true,
  signup_source   text        NOT NULL DEFAULT 'invite',
  created_at      timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX users_email_lower_uq ON users (lower(email));
COMMENT ON TABLE users IS 'People who can sign in, plus bot accounts (e.g. the automation actor).';
COMMENT ON COLUMN users.id IS 'Stable user id (u1, u2 … or u_<random> for new users).';
COMMENT ON COLUMN users.email IS 'Login e-mail, unique case-insensitively.';
COMMENT ON COLUMN users.password_hash IS 'scrypt hash "salt:hash"; NULL for social-only accounts and bots.';
COMMENT ON COLUMN users.role IS 'Site role: admin (site administrator) or member.';
COMMENT ON COLUMN users.active IS 'Deactivated users cannot sign in and are hidden from pickers.';
COMMENT ON COLUMN users.avatar IS 'Stored file name of the uploaded profile photo (served from /api/avatars).';
COMMENT ON COLUMN users.bot IS 'True for system actors such as "Automation for Masar".';
COMMENT ON COLUMN users.signup_source IS 'invite | signup | google | microsoft | apple | slack | seed.';

CREATE TABLE user_preferences (
  user_id        text        PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
  theme          text        NOT NULL DEFAULT 'light' CHECK (theme IN ('light', 'dark', 'system')),
  reduce_motion  boolean     NOT NULL DEFAULT false,
  week_start     text        NOT NULL DEFAULT 'sunday' CHECK (week_start IN ('sunday', 'monday', 'saturday')),
  notify         jsonb       NOT NULL DEFAULT '{}'::jsonb,
  updated_at     timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE user_preferences IS 'Personal settings: theme, motion, week start and notification switches.';
COMMENT ON COLUMN user_preferences.notify IS 'Map of notification type → enabled, e.g. {"comment": false}. Missing = enabled.';

CREATE TABLE sessions (
  token         text        PRIMARY KEY,
  user_id       text        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  user_agent    text        NOT NULL DEFAULT '',
  remember      boolean     NOT NULL DEFAULT true,
  created_at    timestamptz NOT NULL DEFAULT now(),
  last_seen_at  timestamptz,
  expires_at    timestamptz NOT NULL
);
CREATE INDEX sessions_user_idx ON sessions (user_id);
COMMENT ON TABLE sessions IS 'Browser sessions. The token travels as Bearer header, X-Auth-Token, ?access_token or cookie.';
COMMENT ON COLUMN sessions.remember IS 'Remember me: 14-day session instead of 12 hours.';

CREATE TABLE api_tokens (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       text        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  name          text        NOT NULL,
  token_hash    text        NOT NULL UNIQUE,
  prefix        text        NOT NULL,
  created_at    timestamptz NOT NULL DEFAULT now(),
  last_used_at  timestamptz,
  expires_at    timestamptz
);
CREATE INDEX api_tokens_user_idx ON api_tokens (user_id);
COMMENT ON TABLE api_tokens IS 'Personal access tokens (jcpat_…) for scripts; only the SHA-256 hash is stored.';

CREATE TABLE password_resets (
  token_hash  text        PRIMARY KEY,
  user_id     text        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  created_at  timestamptz NOT NULL DEFAULT now(),
  expires_at  timestamptz NOT NULL,
  used_at     timestamptz
);
COMMENT ON TABLE password_resets IS 'One-time password reset links (hash of the token in the e-mailed link).';

CREATE TABLE email_verifications (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email         text        NOT NULL,
  code_hash     text        NOT NULL,
  attempts      integer     NOT NULL DEFAULT 0,
  created_at    timestamptz NOT NULL DEFAULT now(),
  expires_at    timestamptz NOT NULL,
  verified_at   timestamptz,
  signup_token  text UNIQUE,
  used_at       timestamptz
);
CREATE INDEX email_verifications_email_idx ON email_verifications (lower(email));
COMMENT ON TABLE email_verifications IS 'Sign-up: 6-digit e-mail codes and the short-lived token that finishes the sign-up.';

CREATE TABLE user_identities (
  provider       text        NOT NULL,
  subject        text        NOT NULL,
  user_id        text        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  email          text,
  created_at     timestamptz NOT NULL DEFAULT now(),
  last_login_at  timestamptz,
  PRIMARY KEY (provider, subject)
);
CREATE INDEX user_identities_user_idx ON user_identities (user_id);
COMMENT ON TABLE user_identities IS 'Social accounts (Google, Microsoft, Apple, Slack) linked to a user.';

CREATE TABLE oauth_states (
  state       text        PRIMARY KEY,
  provider    text        NOT NULL,
  mode        text        NOT NULL DEFAULT 'login',
  popup       boolean     NOT NULL DEFAULT false,
  remember    boolean     NOT NULL DEFAULT true,
  nonce       text,
  created_at  timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE oauth_states IS 'Pending OAuth authorisation requests (CSRF state + OIDC nonce), valid 10 minutes.';

CREATE TABLE site_settings (
  key         text        PRIMARY KEY,
  value       jsonb       NOT NULL,
  updated_at  timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE site_settings IS 'Site-wide settings: sign-up policy, OAuth providers, global permission scheme …';
-- 002 · Jira configuration: work types, priorities, resolutions, statuses and workflows.

CREATE TABLE issue_types (
  id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name             text        NOT NULL,
  description      text        NOT NULL DEFAULT '',
  icon             text        NOT NULL DEFAULT 'task',
  color            text        NOT NULL DEFAULT '#4BADE8',
  hierarchy_level  integer     NOT NULL DEFAULT 0 CHECK (hierarchy_level IN (-1, 0, 1)),
  position         integer     NOT NULL DEFAULT 0,
  system           boolean     NOT NULL DEFAULT false,
  created_at       timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX issue_types_name_uq ON issue_types (lower(name));
COMMENT ON TABLE issue_types IS 'Work types (Epic, Story, Task, Bug, Subtask, plus custom ones).';
COMMENT ON COLUMN issue_types.hierarchy_level IS '1 = epic level, 0 = standard work, -1 = sub-task level.';
COMMENT ON COLUMN issue_types.icon IS 'Icon key used by the client (epic, story, task, bug, subtask, …).';
COMMENT ON COLUMN issue_types.system IS 'Built-in types cannot be deleted.';

CREATE TABLE priorities (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         text        NOT NULL,
  description  text        NOT NULL DEFAULT '',
  color        text        NOT NULL DEFAULT '#626F86',
  icon         text        NOT NULL DEFAULT 'medium',
  position     integer     NOT NULL DEFAULT 0,
  is_default   boolean     NOT NULL DEFAULT false,
  created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX priorities_name_uq ON priorities (lower(name));
CREATE UNIQUE INDEX priorities_one_default_uq ON priorities (is_default) WHERE is_default;
COMMENT ON TABLE priorities IS 'Priority scheme. position 0 is the most important (Highest).';

CREATE TABLE resolutions (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         text        NOT NULL,
  description  text        NOT NULL DEFAULT '',
  position     integer     NOT NULL DEFAULT 0,
  is_default   boolean     NOT NULL DEFAULT false,
  created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX resolutions_name_uq ON resolutions (lower(name));
CREATE UNIQUE INDEX resolutions_one_default_uq ON resolutions (is_default) WHERE is_default;
COMMENT ON TABLE resolutions IS 'Why work was closed (Done, Won''t Do, Duplicate, Cannot Reproduce). Set when work reaches a done status.';

CREATE TABLE statuses (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         text        NOT NULL,
  description  text        NOT NULL DEFAULT '',
  category     text        NOT NULL CHECK (category IN ('todo', 'in_progress', 'done')),
  created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX statuses_name_uq ON statuses (lower(name));
COMMENT ON TABLE statuses IS 'Workflow statuses shared by all workflows.';
COMMENT ON COLUMN statuses.category IS 'Status category: todo (grey), in_progress (blue) or done (green).';

CREATE TABLE workflows (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         text        NOT NULL,
  description  text        NOT NULL DEFAULT '',
  is_default   boolean     NOT NULL DEFAULT false,
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX workflows_name_uq ON workflows (lower(name));
CREATE UNIQUE INDEX workflows_one_default_uq ON workflows (is_default) WHERE is_default;
COMMENT ON TABLE workflows IS 'A set of statuses (board columns) and the transitions allowed between them.';

CREATE TABLE workflow_statuses (
  workflow_id  integer NOT NULL REFERENCES workflows (id) ON DELETE CASCADE,
  status_id    integer NOT NULL REFERENCES statuses (id) ON DELETE RESTRICT,
  position     integer NOT NULL DEFAULT 0,
  is_initial   boolean NOT NULL DEFAULT false,
  PRIMARY KEY (workflow_id, status_id)
);
CREATE UNIQUE INDEX workflow_statuses_initial_uq ON workflow_statuses (workflow_id) WHERE is_initial;
COMMENT ON TABLE workflow_statuses IS 'Statuses used by a workflow, in board-column order; one is the initial status for new work.';

CREATE TABLE workflow_transitions (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workflow_id     integer NOT NULL REFERENCES workflows (id) ON DELETE CASCADE,
  name            text    NOT NULL,
  from_status_id  integer REFERENCES statuses (id) ON DELETE CASCADE,
  to_status_id    integer NOT NULL REFERENCES statuses (id) ON DELETE CASCADE,
  position        integer NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX workflow_transitions_uq ON workflow_transitions (workflow_id, COALESCE(from_status_id, 0), to_status_id);
COMMENT ON TABLE workflow_transitions IS 'Allowed status changes. from_status_id NULL = global transition (from any status).';
-- 003 · Projects, people & permissions, components, board, teams, sprints and releases.

CREATE TABLE projects (
  key              text PRIMARY KEY CHECK (key ~ '^[A-Z][A-Z0-9]{1,9}$'),
  name             text        NOT NULL,
  type             text        NOT NULL DEFAULT 'software' CHECK (type IN ('software', 'business', 'service')),
  description      text        NOT NULL DEFAULT '',
  lead_id          text        REFERENCES users (id) ON DELETE SET NULL,
  color            text        NOT NULL DEFAULT '#FFAB00',
  category         text        NOT NULL DEFAULT '',
  access           text        NOT NULL DEFAULT 'open' CHECK (access IN ('open', 'limited', 'private')),
  workflow_id      integer     NOT NULL REFERENCES workflows (id),
  custom_permissions boolean   NOT NULL DEFAULT false,
  board_swimlanes  text        NOT NULL DEFAULT 'none' CHECK (board_swimlanes IN ('none', 'assignee', 'epic', 'priority', 'type')),
  next_num         integer     NOT NULL DEFAULT 1,
  created_at       timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX projects_name_uq ON projects (lower(name));
COMMENT ON TABLE projects IS 'Spaces that hold work items. key is the work item key prefix (KAN → KAN-12).';
COMMENT ON COLUMN projects.access IS 'open: everyone is a member · limited: everyone can view · private: only added people.';
COMMENT ON COLUMN projects.workflow_id IS 'Workflow (statuses + transitions) used by this project''s work items and board.';
COMMENT ON COLUMN projects.custom_permissions IS 'True when the project uses its own permission scheme (permission_scheme_entries) instead of the default.';
COMMENT ON COLUMN projects.next_num IS 'Next work item number (the 12 in KAN-12).';

CREATE TABLE project_members (
  project_key  text        NOT NULL REFERENCES projects (key) ON DELETE CASCADE ON UPDATE CASCADE,
  user_id      text        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  role         text        NOT NULL CHECK (role IN ('admin', 'member', 'viewer')),
  added_by     text        REFERENCES users (id) ON DELETE SET NULL,
  added_at     timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (project_key, user_id)
);
CREATE INDEX project_members_user_idx ON project_members (user_id);
COMMENT ON TABLE project_members IS 'Project roles: Administrator, Member or Viewer. The lead is always an administrator.';

CREATE TABLE permission_scheme_entries (
  project_key  text NOT NULL REFERENCES projects (key) ON DELETE CASCADE ON UPDATE CASCADE,
  permission   text NOT NULL,
  role         text NOT NULL CHECK (role IN ('admin', 'member', 'viewer')),
  PRIMARY KEY (project_key, permission, role)
);
COMMENT ON TABLE permission_scheme_entries IS 'Customised permission scheme of a project. A project with no rows uses the default scheme.';

CREATE TABLE project_stars (
  user_id      text NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  project_key  text NOT NULL REFERENCES projects (key) ON DELETE CASCADE ON UPDATE CASCADE,
  starred_at   timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, project_key)
);
COMMENT ON TABLE project_stars IS 'Projects a user starred (shown first in the sidebar).';

CREATE TABLE components (
  id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_key       text        NOT NULL REFERENCES projects (key) ON DELETE CASCADE ON UPDATE CASCADE,
  name              text        NOT NULL,
  description       text        NOT NULL DEFAULT '',
  lead_id           text        REFERENCES users (id) ON DELETE SET NULL,
  default_assignee  text        NOT NULL DEFAULT 'unassigned' CHECK (default_assignee IN ('unassigned', 'component_lead', 'project_lead')),
  created_at        timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX components_name_uq ON components (project_key, lower(name));
COMMENT ON TABLE components IS 'Project components (e.g. Payments, Reporting) with an optional default assignee.';

CREATE TABLE board_column_limits (
  project_key  text    NOT NULL REFERENCES projects (key) ON DELETE CASCADE ON UPDATE CASCADE,
  status_id    integer NOT NULL REFERENCES statuses (id) ON DELETE CASCADE,
  wip_limit    integer NOT NULL CHECK (wip_limit > 0),
  PRIMARY KEY (project_key, status_id)
);
COMMENT ON TABLE board_column_limits IS 'Work-in-progress limits per board column (status).';

CREATE TABLE teams (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         text        NOT NULL,
  description  text        NOT NULL DEFAULT '',
  color        text        NOT NULL DEFAULT '#0C66E4',
  created_by   text        REFERENCES users (id) ON DELETE SET NULL,
  created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX teams_name_uq ON teams (lower(name));
COMMENT ON TABLE teams IS 'Cross-project teams; work items can be assigned to a team.';

CREATE TABLE team_members (
  team_id  integer NOT NULL REFERENCES teams (id) ON DELETE CASCADE,
  user_id  text    NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  PRIMARY KEY (team_id, user_id)
);

CREATE TABLE sprints (
  id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_key       text        NOT NULL REFERENCES projects (key) ON DELETE CASCADE ON UPDATE CASCADE,
  name              text        NOT NULL,
  goal              text        NOT NULL DEFAULT '',
  state             text        NOT NULL DEFAULT 'future' CHECK (state IN ('future', 'active', 'closed')),
  start_date        date,
  end_date          date,
  completed_at      timestamptz,
  position          integer     NOT NULL DEFAULT 0,
  committed_points  double precision,
  committed_count   integer,
  completed_points  double precision,
  completed_count   integer,
  created_at        timestamptz NOT NULL DEFAULT now(),
  CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date)
);
CREATE UNIQUE INDEX sprints_name_uq ON sprints (lower(name));
CREATE UNIQUE INDEX sprints_one_active_uq ON sprints (project_key) WHERE state = 'active';
COMMENT ON TABLE sprints IS 'Scrum sprints. At most one active sprint per project.';
COMMENT ON COLUMN sprints.committed_points IS 'Story points in the sprint when it started (velocity chart).';
COMMENT ON COLUMN sprints.completed_points IS 'Story points done when the sprint was completed.';

CREATE TABLE versions (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_key   text        NOT NULL REFERENCES projects (key) ON DELETE CASCADE ON UPDATE CASCADE,
  name          text        NOT NULL,
  description   text        NOT NULL DEFAULT '',
  status        text        NOT NULL DEFAULT 'unreleased' CHECK (status IN ('unreleased', 'released', 'archived')),
  start_date    date,
  release_date  date,
  released_at   timestamptz,
  position      integer     NOT NULL DEFAULT 0,
  created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX versions_name_uq ON versions (project_key, lower(name));
COMMENT ON TABLE versions IS 'Releases (fix versions) of a project.';
-- 004 · Work items and everything attached to them.

CREATE TABLE issues (
  id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key                 text        NOT NULL UNIQUE,
  num                 integer     NOT NULL,
  project_key         text        NOT NULL REFERENCES projects (key) ON UPDATE CASCADE,
  issue_type_id       integer     NOT NULL REFERENCES issue_types (id),
  summary             text        NOT NULL CHECK (length(summary) BETWEEN 1 AND 255),
  description         text        NOT NULL DEFAULT '',
  status_id           integer     NOT NULL REFERENCES statuses (id),
  priority_id         integer     NOT NULL REFERENCES priorities (id),
  resolution_id       integer     REFERENCES resolutions (id) ON DELETE SET NULL,
  assignee_id         text        REFERENCES users (id) ON DELETE SET NULL,
  reporter_id         text        REFERENCES users (id) ON DELETE SET NULL,
  parent_id           integer     REFERENCES issues (id) ON DELETE SET NULL,
  sprint_id           integer     REFERENCES sprints (id) ON DELETE SET NULL,
  fix_version_id      integer     REFERENCES versions (id) ON DELETE SET NULL,
  team_id             integer     REFERENCES teams (id) ON DELETE SET NULL,
  due_date            date,
  start_date          date,
  story_points        double precision CHECK (story_points IS NULL OR story_points BETWEEN 0 AND 1000),
  rank                double precision NOT NULL,
  original_estimate   integer     CHECK (original_estimate IS NULL OR original_estimate >= 0),
  remaining_estimate  integer     CHECK (remaining_estimate IS NULL OR remaining_estimate >= 0),
  time_spent          integer     NOT NULL DEFAULT 0 CHECK (time_spent >= 0),
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now(),
  resolved_at         timestamptz,
  UNIQUE (project_key, num),
  CHECK (parent_id IS NULL OR parent_id <> id)
);
CREATE INDEX issues_project_idx ON issues (project_key);
CREATE INDEX issues_rank_idx ON issues (rank);
CREATE INDEX issues_sprint_idx ON issues (sprint_id);
CREATE INDEX issues_parent_idx ON issues (parent_id);
CREATE INDEX issues_assignee_idx ON issues (assignee_id);
CREATE INDEX issues_status_idx ON issues (status_id);
CREATE INDEX issues_fix_version_idx ON issues (fix_version_id);
COMMENT ON TABLE issues IS 'Work items (epics, stories, tasks, bugs, sub-tasks).';
COMMENT ON COLUMN issues.key IS 'Human key, project key + number (KAN-12).';
COMMENT ON COLUMN issues.rank IS 'Global ordering used by backlog, board and "ORDER BY Rank" (cf[10019]).';
COMMENT ON COLUMN issues.original_estimate IS 'Original estimate in seconds (1d = 8h, 1w = 5d).';
COMMENT ON COLUMN issues.remaining_estimate IS 'Remaining estimate in seconds.';
COMMENT ON COLUMN issues.time_spent IS 'Total of all worklogs in seconds (kept in sync by the worklog service).';
COMMENT ON COLUMN issues.resolved_at IS 'When the item entered a done-category status; NULL while open.';

CREATE TABLE labels (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        text        NOT NULL CHECK (name ~ '^\S{1,60}$'),
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX labels_name_uq ON labels (lower(name));
COMMENT ON TABLE labels IS 'Site-wide label dictionary (labels have no spaces).';

CREATE TABLE issue_labels (
  issue_id  integer NOT NULL REFERENCES issues (id) ON DELETE CASCADE,
  label_id  integer NOT NULL REFERENCES labels (id) ON DELETE CASCADE,
  position  integer NOT NULL DEFAULT 0,
  PRIMARY KEY (issue_id, label_id)
);
CREATE INDEX issue_labels_label_idx ON issue_labels (label_id);

CREATE TABLE issue_components (
  issue_id      integer NOT NULL REFERENCES issues (id) ON DELETE CASCADE,
  component_id  integer NOT NULL REFERENCES components (id) ON DELETE CASCADE,
  position      integer NOT NULL DEFAULT 0,
  PRIMARY KEY (issue_id, component_id)
);
CREATE INDEX issue_components_component_idx ON issue_components (component_id);

CREATE TABLE comments (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  issue_id    integer     NOT NULL REFERENCES issues (id) ON DELETE CASCADE,
  author_id   text        REFERENCES users (id) ON DELETE SET NULL,
  body        text        NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX comments_issue_idx ON comments (issue_id);

CREATE TABLE history (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  issue_id    integer     NOT NULL REFERENCES issues (id) ON DELETE CASCADE,
  author_id   text        REFERENCES users (id) ON DELETE SET NULL,
  field       text        NOT NULL,
  from_value  text,
  to_value    text,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX history_issue_idx ON history (issue_id);
COMMENT ON TABLE history IS 'Change log of a work item (field, from → to, who, when).';

CREATE TABLE watchers (
  issue_id  integer NOT NULL REFERENCES issues (id) ON DELETE CASCADE,
  user_id   text    NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  PRIMARY KEY (issue_id, user_id)
);
CREATE INDEX watchers_user_idx ON watchers (user_id);

CREATE TABLE votes (
  issue_id    integer     NOT NULL REFERENCES issues (id) ON DELETE CASCADE,
  user_id     text        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  created_at  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (issue_id, user_id)
);

CREATE TABLE issue_links (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_id   integer     NOT NULL REFERENCES issues (id) ON DELETE CASCADE,
  target_id   integer     NOT NULL REFERENCES issues (id) ON DELETE CASCADE,
  type        text        NOT NULL CHECK (type IN ('blocks', 'relates', 'duplicates', 'clones')),
  created_by  text        REFERENCES users (id) ON DELETE SET NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (source_id, target_id, type),
  CHECK (source_id <> target_id)
);
CREATE INDEX issue_links_target_idx ON issue_links (target_id);
COMMENT ON TABLE issue_links IS 'Directed links: source <type> target (KAN-7 blocks KAN-4).';

CREATE TABLE attachments (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  issue_id     integer     NOT NULL REFERENCES issues (id) ON DELETE CASCADE,
  filename     text        NOT NULL,
  mime         text        NOT NULL,
  size         integer     NOT NULL CHECK (size >= 0),
  stored_name  text        NOT NULL,
  uploader_id  text        REFERENCES users (id) ON DELETE SET NULL,
  created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX attachments_issue_idx ON attachments (issue_id);
COMMENT ON COLUMN attachments.stored_name IS 'Random file name on disk (UPLOAD_DIR).';

CREATE TABLE worklogs (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  issue_id    integer     NOT NULL REFERENCES issues (id) ON DELETE CASCADE,
  author_id   text        REFERENCES users (id) ON DELETE SET NULL,
  started_at  timestamptz NOT NULL,
  time_spent  integer     NOT NULL CHECK (time_spent > 0),
  comment     text        NOT NULL DEFAULT '',
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX worklogs_issue_idx ON worklogs (issue_id);
CREATE INDEX worklogs_started_idx ON worklogs (started_at);
COMMENT ON TABLE worklogs IS 'Time logged on work items (seconds).';

CREATE TABLE dev_items (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  issue_id    integer     REFERENCES issues (id) ON DELETE CASCADE,
  kind        text        NOT NULL CHECK (kind IN ('branch', 'commit', 'pr')),
  repo        text        NOT NULL,
  name        text        NOT NULL,
  ref         text,
  status      text,
  author_id   text        REFERENCES users (id) ON DELETE SET NULL,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX dev_items_issue_idx ON dev_items (issue_id);
COMMENT ON TABLE dev_items IS 'Development panel: branches, commits and pull requests linked to work items.';
COMMENT ON COLUMN dev_items.status IS 'PR: open | merged | declined · branch: active.';

CREATE TABLE notifications (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     text        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  actor_id    text        REFERENCES users (id) ON DELETE SET NULL,
  issue_id    integer     REFERENCES issues (id) ON DELETE CASCADE,
  type        text        NOT NULL,
  message     text        NOT NULL,
  read        boolean     NOT NULL DEFAULT false,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX notifications_user_idx ON notifications (user_id, read);
COMMENT ON COLUMN notifications.type IS 'assigned | status | comment | mention.';
-- 005 · Custom fields (Jira-style cf[10100]): definitions, options, per-project use, values.

CREATE TABLE custom_fields (
  id           integer GENERATED BY DEFAULT AS IDENTITY (START WITH 10100) PRIMARY KEY,
  name         text        NOT NULL,
  description  text        NOT NULL DEFAULT '',
