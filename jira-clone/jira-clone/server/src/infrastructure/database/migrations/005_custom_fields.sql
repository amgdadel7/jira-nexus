-- 005 · Custom fields (Jira-style cf[10100]): definitions, options, per-project use, values.

CREATE TABLE custom_fields (
  id           integer GENERATED BY DEFAULT AS IDENTITY (START WITH 10100) PRIMARY KEY,
  name         text        NOT NULL,
  description  text        NOT NULL DEFAULT '',
  type         text        NOT NULL CHECK (type IN ('text', 'paragraph', 'number', 'date', 'select', 'multiselect', 'user', 'checkbox', 'url')),
  created_by   text        REFERENCES users (id) ON DELETE SET NULL,
  created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX custom_fields_name_uq ON custom_fields (lower(name));
COMMENT ON TABLE custom_fields IS 'Custom field definitions. Referenced in JQL as cf[<id>] or by name.';
COMMENT ON COLUMN custom_fields.type IS 'text · paragraph · number · date · select · multiselect · user · checkbox · url.';

CREATE TABLE custom_field_options (
  id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  field_id  integer NOT NULL REFERENCES custom_fields (id) ON DELETE CASCADE,
  value     text    NOT NULL,
  position  integer NOT NULL DEFAULT 0,
  disabled  boolean NOT NULL DEFAULT false
);
CREATE UNIQUE INDEX custom_field_options_uq ON custom_field_options (field_id, lower(value));
COMMENT ON TABLE custom_field_options IS 'Choices of select / multi-select fields. Disabled options stay on existing work.';

CREATE TABLE project_custom_fields (
  project_key  text    NOT NULL REFERENCES projects (key) ON DELETE CASCADE ON UPDATE CASCADE,
  field_id     integer NOT NULL REFERENCES custom_fields (id) ON DELETE CASCADE,
  position     integer NOT NULL DEFAULT 0,
  required     boolean NOT NULL DEFAULT false,
  PRIMARY KEY (project_key, field_id)
);
COMMENT ON TABLE project_custom_fields IS 'Which custom fields a project uses (field context), their order and whether they are required.';

CREATE TABLE custom_field_values (
  issue_id    integer     NOT NULL REFERENCES issues (id) ON DELETE CASCADE,
  field_id    integer     NOT NULL REFERENCES custom_fields (id) ON DELETE CASCADE,
  value       jsonb       NOT NULL,
  updated_at  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (issue_id, field_id)
);
CREATE INDEX custom_field_values_field_idx ON custom_field_values (field_id);
COMMENT ON TABLE custom_field_values IS 'Value of a custom field on a work item: string, number, boolean, ISO date, option id, option id array or user id.';
